# Build the lab3 exception/interrupt waveform program.
# Layout: tests at 0xbfc00000, handler fixed at 0xbfc00380.

BASE = 0xBFC00000
ZERO, T0, T1, T2 = 0, 8, 9, 10
S0, S1, S2 = 16, 17, 18
K0, K1 = 26, 27


def u16(x):
    return x & 0xFFFF


def rtype(rs, rt, rd, sh, fn):
    return (rs << 21) | (rt << 16) | (rd << 11) | (sh << 6) | fn


def itype(op, rs, rt, imm):
    return (op << 26) | (rs << 21) | (rt << 16) | u16(imm)


def lui(rt, imm):
    return itype(0b001111, 0, rt, imm)


def ori(rt, rs, imm):
    return itype(0b001101, rs, rt, imm)


def addiu(rt, rs, imm):
    return itype(0b001001, rs, rt, imm)


def andi(rt, rs, imm):
    return itype(0b001100, rs, rt, imm)


def add(rd, rs, rt):
    return rtype(rs, rt, rd, 0, 0b100000)


def sw(rt, rs, off):
    return itype(0b101011, rs, rt, off)


def lw(rt, rs, off):
    return itype(0b100011, rs, rt, off)


def mtc0(rt, rd):
    return 0x40800000 | (rt << 16) | (rd << 11)


def mfc0(rt, rd):
    return 0x40000000 | (rt << 16) | (rd << 11)


def eret():
    return 0x42000018


code = []
labels = {}
fix_beq = []
fix_imm = []


def at(name):
    labels[name] = len(code)


def e(word):
    code.append(word & 0xFFFFFFFF)


def beq(rs, rt, lab):
    fix_beq.append((len(code), rs, rt, lab))
    e(0)


def la(reg, lab):
    fix_imm.append((len(code), "lui", reg, lab))
    e(0)
    fix_imm.append((len(code), "ori", reg, lab))
    e(0)


at("start")
e(lui(K0, 0xFFFF))
e(ori(K0, K0, 0xFFFF))
e(mtc0(K0, 11))                # Compare = all-ones, TI stays clear
e(lui(K0, 0x0040))
e(mtc0(K0, 12))                # BEV = 1, IE = 0
e(lui(S0, 0x8000))
e(lui(S1, 0x8000))
e(ori(S1, S1, 0x0100))
e(addiu(S2, ZERO, 0))          # regfile has no reset; s2 selects the interrupt phase
e(addiu(T0, ZERO, 0x1111))

at("do_sys")
e(0x0000000C)                 # syscall
e(sw(T0, S0, 0x200))          # killed in ID, then re-executed after ERET
e(addiu(T0, ZERO, 1))
e(sw(T0, S0, 0))

at("do_brk")
e(0x0000000D)                 # break
e(0)
e(addiu(T0, ZERO, 2))
e(sw(T0, S0, 4))

at("do_ov")
e(lui(T1, 0x8000))
e(add(T2, T1, T1))            # 0x80000000 + 0x80000000
e(0)
e(addiu(T0, ZERO, 3))
e(sw(T0, S0, 8))

at("do_adel")
e(lw(T0, ZERO, 1))
e(0)
e(addiu(T0, ZERO, 4))
e(sw(T0, S0, 12))

at("do_ri")
e(0xFFFFFFFF)                 # reserved
e(0)
e(addiu(T0, ZERO, 5))
e(sw(T0, S0, 16))

e(mtc0(ZERO, 9))
e(lui(K0, 0xFFFF))
e(ori(K0, K0, 0xFFFF))
e(mtc0(K0, 11))
e(lui(K0, 0x0040))
e(ori(K0, K0, 0xFF01))
e(mtc0(K0, 12))
e(addiu(K0, ZERO, 0x100))     # Cause.IP0
e(mtc0(K0, 13))
e(0)
e(0)
at("spin_soft")
beq(ZERO, ZERO, "spin_soft")
e(0)

at("ti_start")
e(mtc0(ZERO, 9))
e(addiu(K0, ZERO, 80))
e(mtc0(K0, 11))
e(0)
e(0)
at("spin_ti")
beq(ZERO, ZERO, "spin_ti")
e(0)

at("hw_start")
at("spin_hw")
beq(ZERO, ZERO, "spin_hw")
e(0)

at("done")
e(addiu(T0, ZERO, 0x55))
e(sw(T0, S0, 20))
at("spin_done")
beq(ZERO, ZERO, "spin_done")
e(0)

if len(code) > 0xE0:
    raise SystemExit("main overlaps the handler: %d words" % len(code))
while len(code) < 0xE0:
    e(0)

at("handler")
e(mfc0(K0, 13))
e(mfc0(K1, 14))
e(sw(K0, S1, 0))
e(addiu(S1, S1, 4))
e(sw(K1, S1, 0))
e(addiu(S1, S1, 4))
e(andi(K0, K0, 0x7C))
beq(K0, ZERO, "is_int")
e(0)
e(addiu(K1, K1, 4))
e(mtc0(K1, 14))
e(eret())
e(0)

at("is_int")
e(addiu(T0, ZERO, 1))
beq(S2, ZERO, "do_soft")
e(0)
beq(S2, T0, "do_ti")
e(0)
e(lui(K0, 0x0040))
e(mtc0(K0, 12))               # IE = 0, BEV stays 1
e(addiu(S2, S2, 1))
la(K1, "done")
e(mtc0(K1, 14))
e(eret())
e(0)

at("do_soft")
e(mtc0(ZERO, 13))
e(addiu(S2, S2, 1))
la(K1, "ti_start")
e(mtc0(K1, 14))
e(eret())
e(0)

at("do_ti")
e(lui(K0, 0xFFFF))
e(ori(K0, K0, 0xFFFF))
e(mtc0(K0, 11))              # clear TI
e(addiu(S2, S2, 1))
la(K1, "hw_start")
e(mtc0(K1, 14))
e(eret())
e(0)

for idx, rs, rt, lab in fix_beq:
    pc = BASE + idx * 4
    tgt = BASE + labels[lab] * 4
    off = (tgt - (pc + 4)) >> 2
    code[idx] = itype(0b000100, rs, rt, off)

for idx, kind, reg, lab in fix_imm:
    addr = BASE + labels[lab] * 4
    if kind == "lui":
        code[idx] = lui(reg, addr >> 16)
    else:
        code[idx] = ori(reg, reg, addr)

out_hex = r"D:\Architecture\lab3\sim\wave_imem.hex"
with open(out_hex, "w", encoding="ascii") as f:
    for i, word in enumerate(code):
        if i == 0 or word != 0:
            f.write("@%08x\n%08x\n" % (i, word))

out_vh = r"D:\Architecture\lab3\sim\wave_labels.vh"
with open(out_vh, "w", encoding="ascii") as f:
    f.write("// generated by gen_wave_imem.py\n")
    for name in ("do_sys", "do_brk", "do_ov", "do_adel", "do_ri",
                 "spin_soft", "spin_ti", "spin_hw", "done", "handler"):
        f.write("`define WAVE_%s 32'h%08x\n" % (name.upper(), BASE + labels[name] * 4))

print("words", len(code))
for name in ("do_sys", "do_brk", "do_ov", "do_adel", "do_ri",
             "spin_soft", "ti_start", "spin_ti", "hw_start", "done", "handler"):
    print("%-10s %08x" % (name, BASE + labels[name] * 4))
